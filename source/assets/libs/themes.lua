local C = Color.new

local function theme(t)
	-- legacy aliases
	t.COLOR_LEFT_BACK = t.COLOR_RAIL
	t.COLOR_SELECTED = t.COLOR_SURFACE2
	t.COLOR_PANEL = t.COLOR_SURFACE
	t.COLOR_LABEL = t.COLOR_ACCENT
	t.COLOR_SELECTOR = t.COLOR_ACCENT
	t.COLOR_ICON_EXTRACT = t.COLOR_FONT
	t.COLOR_COVER = t.COLOR_COVER or t.COLOR_SURFACE2
	return t
end

